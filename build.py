"""Build everything that gets published.

  python build.py            build dist/ from the pages, components and switch
  python build.py --dev      also allow localhost (for local testing only; never publish a --dev build)

Output:
  dist/site/                 the public website. Upload or deploy this folder as the host's root.
    pl.js                    the lookup file: which pages have a new look, plus the kill switch. Cache 5 min.
    pages/<id>.<hash>.js     each page's new look. The name changes whenever it changes. Cache 1 year.
    admin/                   the dashboard (sign-in needed to change anything)
    CNAME, .nojekyll         GitHub Pages settings
    _headers                 cache rules for Cloudflare Pages or Netlify
    .htaccess                cache rules for Apache (most shared hosting)
  dist/cms8/hosted-embed.txt the Embed block for CMS8. The same for every page.
  dist/cms8/<id>-embed.txt   self-contained Embed blocks (no host needed), one per page

Turning things off: set "off": true in switch.json (all pages), or "status": "off" in a page's page.json.
"""
import argparse, hashlib, json, shutil, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "css-refresh" / "tools"))
from build_cms8_embed import make_bundle, pl  # noqa: E402  (shared bundle logic and the Page Layers library)

ap = argparse.ArgumentParser()
ap.add_argument("--dev", action="store_true", help="allow localhost too (testing only)")
args = ap.parse_args()

cfg = json.loads((ROOT / "layers.config.json").read_text(encoding="utf-8"))
switch = json.loads((ROOT / "switch.json").read_text(encoding="utf-8"))
host, sites = cfg["host"], list(cfg["sites"])
if args.dev:
    sites += ["localhost", "127.0.0.1"]

dist = ROOT / "dist"
site = dist / "site"
if dist.exists():
    shutil.rmtree(dist)
(site / "pages").mkdir(parents=True)
(dist / "cms8").mkdir()

# 1. One file per live page
pages, report = {}, []
for pj in sorted(pl.PAGES.glob("*/page.json")):
    pid = pj.parent.name
    page = pl.load(pj)
    if page.get("status", "live") == "off":
        report.append(f"  {pid}: off (skipped)")
        continue
    bundle, _ = make_bundle(pid)
    name = f"{pid}.{hashlib.sha256(bundle.encode('utf-8')).hexdigest()[:12]}.js"
    (site / "pages" / name).write_text(bundle, encoding="utf-8", newline="\n")
    for path in page["paths"]:
        pages[path.rstrip("/") or "/"] = "pages/" + name
    report.append(f"  {pid}: pages/{name} ({len(bundle) / 1024:.0f} KB) for {', '.join(page['paths'])}")
    # the self-contained CMS8 block for the same page (fallback when no host is wanted)
    subprocess.run([sys.executable, "-I", str(ROOT / "css-refresh" / "tools" / "build_cms8_embed.py"), pid],
                   check=True, capture_output=True)
    shutil.move(str(ROOT / "css-refresh" / "cms8-embed" / f"{pid}-embed.txt"), str(dist / "cms8" / f"{pid}-embed.txt"))
shutil.rmtree(ROOT / "css-refresh" / "cms8-embed", ignore_errors=True)

# 2. The lookup file
manifest = {"off": bool(switch.get("off")), "pages": pages}
pljs = """/* Study.com Page Layers lookup, served from %(host)s (5-minute cache). Generated by build.py.
   Lists which pages get a new look. Pages not listed are left exactly as they are.
   ?layers=off in a page address skips it for that view. */
(function () {
  'use strict';
  var M = %(manifest)s, SITES = %(sites)s;
  if (M.off || SITES.indexOf(location.hostname) < 0) return;
  if (/[?&]layers=off\\b/.test(location.search)) return;
  var path = location.pathname.replace(/\\/+$/, '') || '/';
  var file = M.pages[path];
  if (!file) return;
  var me = document.currentScript, base = me ? me.src.replace(/[^\\/?#]*([?#].*)?$/, '') : 'https://%(host)s/';
  var src = base + file;
  if (document.readyState === 'loading') {
    /* Added while the page is still being read, so the CSS applies before the article paints. */
    document.write('<script src="' + src + '"><\\/script>');
  } else {
    var s = document.createElement('script'); s.src = src; document.head.appendChild(s);
  }
})();
""" % {"host": host, "manifest": json.dumps(manifest, separators=(",", ":")), "sites": json.dumps(sites)}
(site / "pl.js").write_text(pljs, encoding="utf-8", newline="\n")

# 3. The dashboard, with this repository's details baked in
shutil.copytree(ROOT / "admin", site / "admin")
(site / "admin" / "site.json").write_text(json.dumps({
    "repo": cfg["repo"], "branch": cfg.get("branch", "main"), "host": host, "sites": cfg["sites"]}, indent=2), encoding="utf-8")

# 4. Hosting settings: GitHub Pages, Cloudflare Pages / Netlify, Apache
if "/" not in host and not host.endswith(".github.io"):   # only a custom domain gets a CNAME file
    (site / "CNAME").write_text(host + "\n", encoding="utf-8")
(site / ".nojekyll").write_text("", encoding="utf-8")
(site / "_headers").write_text(
    "/pl.js\n  Cache-Control: public, max-age=300\n  Access-Control-Allow-Origin: *\n\n"
    "/pages/*\n  Cache-Control: public, max-age=31536000, immutable\n  Access-Control-Allow-Origin: *\n\n"
    "/admin/*\n  Cache-Control: no-cache\n  X-Frame-Options: DENY\n", encoding="utf-8")
(site / ".htaccess").write_text("""# Cache rules for Apache (most shared hosting). Needs mod_headers.
<IfModule mod_headers.c>
  <Files "pl.js">
    Header set Cache-Control "public, max-age=300"
    Header set Access-Control-Allow-Origin "*"
  </Files>
  <FilesMatch "^[a-z0-9-]+\\.[0-9a-f]{12}\\.js$">
    Header set Cache-Control "public, max-age=31536000, immutable"
    Header set Access-Control-Allow-Origin "*"
  </FilesMatch>
</IfModule>
AddType text/javascript .js
""", encoding="utf-8")

# 5. The CMS8 block that points at the host
(dist / "cms8" / "hosted-embed.txt").write_text(
    "[{Embed\n\n"
    f"<!-- Study.com Page Layers, hosted on {host}. The same block works on every page: the host decides what loads. "
    "Keep it at the top of the article body. -->\n"
    f'<script src="https://{host}/pl.js"></script>\n\n}}]\n', encoding="utf-8", newline="\n")

print("\n".join(report))
print(f"pl.js: {len(pages)} address(es) listed; switch {'OFF - nothing loads' if manifest['off'] else 'on'}"
      f"{'; DEV build (localhost allowed) - do not publish' if args.dev else ''}")
print(f"built dist/site (publish this) and dist/cms8 (Embed blocks)")
